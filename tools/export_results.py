"""Write static/js/generated/msp_results.js from the paper's E10 and E12 result files.

The page's baseline table, rate-quality frontier and executed-grasp coverage table read only this
generated file, and this file reads only msp_framework/results/rebuttal/{r2,r4,r5,r6}.json, the
same artefacts the ICRA manuscript's Table "baselines" and Figs. "frontier" and "selective" are
built from. Nothing is typed in by hand.

    python3 tools/export_results.py --repo ../msp_framework
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HEADER = "/* GENERATED by tools/export_results.py from msp_framework/results/rebuttal. Do not edit. */\n"


def r(x: float, n: int = 8) -> float:
    return round(float(x), n)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=Path("static/js/generated/msp_results.js"))
    args = ap.parse_args()
    res = args.repo / "results" / "rebuttal"
    load = lambda name: json.loads((res / name).read_text())  # noqa: E731

    r2, r4, r5, r6 = load("r2.json"), load("r4.json"), load("r5.json"), load("r6.json")

    by_name = {row["method"]: row for row in r2}
    sweep = {s["bits_per_dim"]: s for s in r6["sweep"]}
    fp32, two_bit = sweep[32], sweep[2]

    def row(key: str, label: str, ours: bool = False, payload: tuple | None = None) -> dict:
        src = by_name[key]
        out = {"method": label, "ours": ours, "seeds": 1,
               "pooled": r(src["pooled_auc"]), "within": r(src["within_scene_auc"]),
               "top1": r(src["top1_success"])}
        if payload:
            out["bytes_fp32"], out["bytes_2bit"] = payload
        return out

    baselines = [
        {
            "method": "GQ-CNN architecture, retrained on this corpus", "ours": False,
            "seeds": len(r5["seeds"]),
            "pooled": r(r5["pooled_auc"]), "pooled_sd": r(r5["pooled_auc_sd"]),
            "within": r(r5["within_scene_auc"]), "within_sd": r(r5["within_scene_auc_sd"]),
            "top1": r(r5["top1_success"]), "top1_sd": r(r5["top1_success_sd"]),
            "bytes_fp32": round(fp32["gqcnn"]["payload_bits"] / 8),
            "bytes_2bit": round(two_bit["gqcnn"]["payload_bits"] / 8),
        },
        row("MSP (ours)", "MSP", ours=True,
            payload=(round(fp32["msp"]["payload_bits"] / 8), round(two_bit["msp"]["payload_bits"] / 8))),
        row("Direct success CNN (no bottleneck)", "Same network, rate term removed"),
        row("Ferrari-Canny on reconstructed box", "Ferrari-Canny on the reconstructed box"),
        row("Random", "Random"),
    ]

    frontier = [
        {"bits_per_dim": s["bits_per_dim"],
         "msp": {"bits": r(s["msp"]["payload_bits"], 2), "within": r(s["msp"]["within_scene_auc"]),
                 "top1": r(s["msp"]["top1_success"]), "pooled": r(s["msp"]["pooled_auc"])},
         "gqcnn": {"bits": r(s["gqcnn"]["payload_bits"], 2), "within": r(s["gqcnn"]["within_scene_auc"]),
                   "top1": r(s["gqcnn"]["top1_success"]), "pooled": r(s["gqcnn"]["pooled_auc"])}}
        for s in r6["sweep"]
    ]

    executed = [
        {"alpha": row_["alpha"], "target": r(1 - row_["alpha"], 2),
         **{k: {"coverage": r(row_[k]["coverage"]), "certified": r(row_[k]["certified_fraction"]),
                "precision": r(row_[k]["certified_precision"])}
            for k in ("pairwise", "executed", "selective")}}
        for row_ in r4
    ]

    data = {"n_actions": r6["n_actions"], "baselines": baselines, "frontier": frontier,
            "executed": executed}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(HEADER + "window.MSP_RESULTS = " + json.dumps(data, indent=1) + ";\n")

    for b in baselines:
        print(f"{b['method']:<48} pooled {b['pooled']:.3f} within {b['within']:.3f} "
              f"top1 {b['top1']:.3f} seeds {b['seeds']} bytes {b.get('bytes_fp32', '-')}/{b.get('bytes_2bit', '-')}")
    for e in executed:
        print(e["alpha"], {k: (e[k]["coverage"], e[k]["certified"]) for k in ("pairwise", "executed", "selective")})


if __name__ == "__main__":
    main()
